"""Captured SM3 message sequences needed to open and close a session.

These byte strings are data **captured from the adapter itself** (the frames
the manufacturer's own driver puts on the wire, plus the app's own recorded
poll and write template). They are facts about the device, required for
interoperability: the firmware checks the ``h4`` fingerprint on every message,
so a channel is opened by replaying known-good frames rather than by
hand-rolling them. See ``THIRD_PARTY_LICENSES.txt`` for the provenance of the
protocol recovery this data comes from.

The byte values are verbatim device output, transcribed unchanged; the
surrounding code is an independent implementation.
"""

from __future__ import annotations

from typing import List


def _h(*parts: str) -> bytes:
    return bytes.fromhex("".join(parts))


